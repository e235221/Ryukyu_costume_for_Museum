import assert from 'node:assert/strict';
import {FaceSlots,faceGeometry} from '../assets/js/face-slots.mjs';
const face=(x,y=.4)=>({x,y,size:.1});
const tracker=new FaceSlots(3);
let slots=tracker.update([face(.8),face(.2),face(.5)],0);
assert.deepEqual(slots.map(s=>s.face.x),[.2,.5,.8]);
slots=tracker.update([face(.79),face(.51),face(.21)],100);
assert.deepEqual(slots.map(s=>s.face.x),[.21,.51,.79]);
slots=tracker.update([face(.78),face(.22)],200);
assert.deepEqual(slots.map(s=>s.visible),[true,false,true]);
slots=tracker.update([face(.52),face(.23),face(.77)],400);
assert.deepEqual(slots.map(s=>s.face.x),[.23,.52,.77]);
slots=tracker.update([],1500);
assert(slots.every(s=>!s.face&&!s.visible));
slots=tracker.update([face(.9),face(.1)],1600);
assert.deepEqual(slots.map(s=>s.face?.x),[.1,.9,undefined]);
tracker.reset();
slots=tracker.update([face(.4),face(.41)],1700);
assert.equal(slots.filter(s=>s.visible).length,2);
assert.notEqual(slots[0].face,slots[1].face);
const landmarks=Array.from({length:478},()=>({x:.25,y:.5}));
landmarks[234]={x:.2,y:.5};landmarks[454]={x:.3,y:.5};landmarks[10]={x:.25,y:.4};landmarks[152]={x:.25,y:.6};
const geometry=faceGeometry(landmarks);
assert.equal(geometry.x,.75);assert.equal(geometry.y,.5);
console.log('PASS: 3 faces, detection order changes, temporary loss, re-entry, reset, unique assignment, mirror geometry.');
